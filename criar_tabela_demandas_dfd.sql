-- 1. Criação da tabela de demandas de licitação (DFD)
CREATE TABLE IF NOT EXISTS public.demandas_dfd (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    
    -- Dados do solicitante
    nome_solicitante TEXT NOT NULL,
    setor_solicitante TEXT NOT NULL,
    siape TEXT NOT NULL,
    email TEXT NOT NULL,
    categoria TEXT NOT NULL DEFAULT 'Consumo',
    justificativa TEXT NOT NULL,
    
    -- Status da demanda no fluxo administrativo
    -- Valores possíveis: 'Cadastrada', 'Em Análise', 'Aprovada', 'Encaminhada para Licitação', 'Finalizada', 'Rejeitada'
    status TEXT NOT NULL DEFAULT 'Cadastrada',
    
    -- Quantitativos e valores
    total_itens INTEGER NOT NULL DEFAULT 0,
    estimativa_total NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    
    -- Cesta de materiais em JSON estruturado
    itens JSONB NOT NULL DEFAULT '[]'::jsonb,
    
    -- Vínculo com o usuário da Secretaria/IAD (opcional)
    usuario_id UUID REFERENCES public.secretaria_usuarios(id) ON DELETE SET NULL,
    
    -- Observações e despachos administrativos
    observacoes_admin TEXT
);

-- 2. Criação de índices para consultas ágeis
CREATE INDEX IF NOT EXISTS idx_demandas_dfd_status ON public.demandas_dfd (status);
CREATE INDEX IF NOT EXISTS idx_demandas_dfd_email ON public.demandas_dfd (email);
CREATE INDEX IF NOT EXISTS idx_demandas_dfd_siape ON public.demandas_dfd (siape);
CREATE INDEX IF NOT EXISTS idx_demandas_dfd_setor ON public.demandas_dfd (setor_solicitante);
CREATE INDEX IF NOT EXISTS idx_demandas_dfd_created ON public.demandas_dfd (created_at DESC);

-- 3. Habilitação de Row Level Security (RLS)
ALTER TABLE public.demandas_dfd ENABLE ROW LEVEL SECURITY;

-- 4. Políticas de Acesso RLS
DROP POLICY IF EXISTS "Permitir leitura publica de demandas_dfd" ON public.demandas_dfd;
CREATE POLICY "Permitir leitura publica de demandas_dfd"
ON public.demandas_dfd
FOR SELECT
USING (true);

DROP POLICY IF EXISTS "Permitir criacao de novas demandas_dfd" ON public.demandas_dfd;
CREATE POLICY "Permitir criacao de novas demandas_dfd"
ON public.demandas_dfd
FOR INSERT
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir atualizacao de demandas_dfd" ON public.demandas_dfd;
CREATE POLICY "Permitir atualizacao de demandas_dfd"
ON public.demandas_dfd
FOR UPDATE
USING (true)
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir exclusao de demandas_dfd" ON public.demandas_dfd;
CREATE POLICY "Permitir exclusao de demandas_dfd"
ON public.demandas_dfd
FOR DELETE
USING (true);

-- 5. Trigger para atualização automática da coluna updated_at
CREATE OR REPLACE FUNCTION public.handle_demandas_dfd_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_demandas_dfd_updated_at ON public.demandas_dfd;
CREATE TRIGGER trigger_demandas_dfd_updated_at
BEFORE UPDATE ON public.demandas_dfd
FOR EACH ROW
EXECUTE FUNCTION public.handle_demandas_dfd_updated_at();

-- Concluído! A tabela está pronta para receber os pedidos de compras e demandas de materiais.
